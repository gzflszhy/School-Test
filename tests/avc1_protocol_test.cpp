#include "avc1_protocol.hpp"

#include <array>
#include <cassert>
#include <cstdint>
#include <limits>

using namespace maixcam_marker;

int main() {
    constexpr std::array<std::uint8_t, kAvc1FrameSize> first{{
        0x41, 0x56, 0x43, 0x31, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x3F, 0x00, 0x00, 0x80, 0xBE,
        0x01, 0x00, 0x00, 0x00, 0x2E, 0xB8, 0x88, 0x88}};
    constexpr std::array<std::uint8_t, kAvc1FrameSize> stopped{{
        0x41, 0x56, 0x43, 0x31, 0x02, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0xDE, 0xB9, 0xEB, 0x44}};
    constexpr std::array<std::uint8_t, kAvc1FrameSize> wrapped{{
        0x41, 0x56, 0x43, 0x31, 0x00, 0x00, 0x00, 0x00,
        0xCD, 0xCC, 0x4C, 0xBF, 0xCD, 0xCC, 0x4C, 0x3F,
        0x01, 0x00, 0x00, 0x00, 0xED, 0x6D, 0x71, 0x00}};

    assert(packAvc1Frame(1U, 0.5F, -0.25F, true) == first);
    assert(packAvc1Frame(2U, 0.0F, 0.0F, false) == stopped);
    assert(packAvc1Frame(0U, -0.8F, 0.8F, true) == wrapped);

    const auto invalid = packAvc1Frame(
        3U, std::numeric_limits<float>::quiet_NaN(), 0.4F, true);
    assert(invalid[16U] == 0U);
    for (std::size_t i = 8U; i < 20U; ++i) assert(invalid[i] == 0U);
    return 0;
}
